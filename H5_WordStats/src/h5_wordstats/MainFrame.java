    private void updateStatistics() {
        String text = textArea.getText();
        long start = System.nanoTime();
        ArrayList<StatsEntry> entries;

        if (versionComboBox.getSelectedIndex() == 0) {
            entries = wordsStats.calculateWithHashMap(text);
        } else {
            entries = wordsStats.calculateWithList(text);
        }

        double elapsedMilliseconds = (System.nanoTime() - start) / 1000000.0;
        int totalWords = 0;
        statsListModel.clear();

        for (StatsEntry entry : entries) {
            statsListModel.addElement(entry.toString());
            totalWords += entry.count;
        }

        String totalLabel = totalWords > 1 ? " mots" : " mot";
        String uniqueLabel = entries.size() > 1 ? " mots différents" : " mot différent";
        summaryLabel.setText(totalWords + totalLabel + "  |  " + entries.size() + uniqueLabel);
        timeLabel.setText(String.format(Locale.FRANCE, "Calcul : %.3f ms", elapsedMilliseconds));
    }

